def P(label, kind, lo, hi, default, show=None):
    return dict(label=label, kind=kind, lo=float(lo), hi=float(hi), default=float(default), show=show)


def C(label, choices, idx, show=None):
    return dict(label=label, kind="Choice", choices=list(choices), idx=int(idx), show=show)


def FX(name, cat, viz, desc, ctrls, macro=None, modes=None, mix=1.0):
    return dict(name=name, cat=cat, viz=viz, desc=desc, ctrls=ctrls, macro=macro,
                modes=modes or [], mix=float(mix))


