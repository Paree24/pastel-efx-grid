"""FROZEN copy of the v2 (state version 2) effect specification.

Do not edit: tools/gen_registry.py uses it to migrate sessions saved with
the v2 control layout (values are matched by control name).

tools/gen_registry.py turns this into Source/EffectRegistry.cpp. (fx_data.py is
kept only for the HTML/SVG mockup generators.)

Each effect lists the controls its DSP actually reads, in physical units:

    P(label, kind, lo, hi, default, show=None)    continuous control
    C(label, [choices], default_index, show=None) discrete control

kinds:  Hz Ms Sec Ratio Factor  - logarithmic taper
        Db Pct BiPct Pan Semis Cents Deg Int Lin Oct Vowel Note BiHz - linear
        (Lin takes an optional unit suffix: P("Tilt", "Lin:dB/oct", ...))

show = ("mode", ["Sync"]) or ("Sync", ["On"]) — the control only matters when
the mode / another choice control has one of those values; the UI dims it
otherwise.

macro = (name, {control_label: physical_target, ...}) is the *default* macro
routing; at macro 100% each listed control is pushed by (target - default).
Users re-route the macro per slot in the plugin, so this is only a starting
point. Analysis effects have no macro (they are meters).
"""

